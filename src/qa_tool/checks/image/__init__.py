"""Модуль «Картинка» (этап 7): эффект настроек изображения на кадре.

`IMAGE-EFFECT-1` идёт в синхронной фазе: все камеры снимают одну сцену одновременно, поэтому их
можно честно сравнить (AD-2). Галочку «изменяющие» проверка смотрит сама (`writes=False`): без
неё она не пропускается, а снимает кадр и текущие значения — это нужно протоколу и сравнению.
"""

from qa_tool.checks.image.engine import CHECK_ID, Engine
from qa_tool.core.checks import REGISTRY, CheckContext, CheckResult, Phase, Severity
from qa_tool.core.models import Place

# Потолок срока от потолков сроков (спека, «Этап 6, сроки»): 2 кадра «до» и на каждую из
# 9 настроек до 3 положений, возврат и контрольный кадр — по 10 с ожидания стабильности и 12 с
# ключевого кадра; обычный проход — 5–6 мин.
TIMEOUT_S = 1700.0


@REGISTRY.check(
    CHECK_ID,
    "image",
    "Картинка: эффект настроек",
    "Настройки изображения из ONVIF Imaging — яркость, контраст, насыщенность, резкость, баланс "
    "белого (красный и синий), WDR, компенсация засветки, шумоподавление — по очереди ставятся в "
    "0 %, 50 % и 100 % диапазона, который объявила камера. В каждом положении снимается кадр и "
    "измеряется величина; ожидается, что она меняется в нужную сторону на каждом шаге больше "
    "порога. После каждой настройки значение возвращается и сверяется. Режим экспозиции не "
    "меняется.",
    phase=Phase.SYNC,
    places={Place.COLOR_BOX},
    severity=Severity.MAJOR,
    timeout_s=TIMEOUT_S,
    group="Настройки изображения",
    help_id="image",
    read_only_note=(
        "Без этой галочки «Картинка» только снимет текущий кадр и прочитает значения настроек: "
        "эффект настроек не проверяется, строки настроек будут «пропущена»."
    ),
    writes_note=(
        "«Картинка» будет менять яркость, контраст и другие настройки изображения и возвращать "
        "каждую после проверки. Режим экспозиции, сеть и пароли не меняются."
    ),
)
def image_effect(ctx: CheckContext) -> CheckResult:
    """Проверка картинки одной камеры (движок — `engine.Engine`)."""
    return Engine(ctx).run()
