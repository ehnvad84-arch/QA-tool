"""Модуль «Кодеки» (этап 8): качество потока на единицу битрейта.

`CODEC-QUALITY-1` идёт в синхронной фазе после «Картинки»: все камеры снимают одну неподвижную
сцену бокса, поэтому кривые разных камер сравнимы (AD-2). Галочку «изменяющие» проверка смотрит
сама (`writes=False`): без неё кодировщики не меняются, но их текущие настройки идут в протокол.
"""

from qa_tool.checks.codec.engine import CHECK_ID, TIMEOUT_S, Engine
from qa_tool.core.checks import REGISTRY, CheckContext, CheckResult, Phase, Severity
from qa_tool.core.models import Place

# «Картинка» регистрируется с порядком по умолчанию (100); «Кодеки» — сразу за ней.
ORDER = 110


@REGISTRY.check(
    CHECK_ID,
    "codec",
    "Кодеки: качество на битрейт",
    "По каждому профилю и каждому кодеку (H.264, H.265), который объявляет камера, поток "
    "снимается на ступенях битрейта — от максимума камеры к минимуму, битрейт постоянный — и "
    "каждая ступень сравнивается с лучшим потоком этого профиля по VMAF, SSIM и PSNR. "
    "Ожидается: качество не ниже порога для разрешения, растёт с битрейтом, поток соответствует "
    "заданному битрейту. После проверки кодек и битрейт возвращаются и сверяются; разрешение и "
    "частота кадров не меняются.",
    phase=Phase.SYNC,
    places={Place.COLOR_BOX},
    severity=Severity.MAJOR,
    order=ORDER,
    timeout_s=TIMEOUT_S,
    group="Качество сжатия",
    help_id="codec",
    read_only_note=(
        "Без этой галочки «Кодеки» только прочитают текущие настройки кодировщиков: качество "
        "на битрейт не проверяется, строки профилей будут «пропущена»."
    ),
    writes_note=(
        "«Кодеки» будут менять кодек и битрейт в каждом профиле и возвращать их после "
        "проверки. Разрешение, частота кадров, сеть и пароли не меняются. Пока идёт проверка, "
        "другие зрители камеры увидят поток другого качества."
    ),
)
def codec_quality(ctx: CheckContext) -> CheckResult:
    """Проверка кодеков одной камеры (движок — `engine.Engine`)."""
    return Engine(ctx).run()
